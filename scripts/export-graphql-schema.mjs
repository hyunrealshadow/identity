import { spawnSync } from 'node:child_process'
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const catalog = process.argv.includes('--error-catalog')
const management = process.argv.includes('--management-catalog')
const args = ['run', '--quiet', '-p', 'identity-web', '--bin', 'identity-schema']
if (catalog) args.push('--', '--error-catalog')
if (management) args.push('--', '--management-catalog')
const result = spawnSync('cargo', args, {
  cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024,
})
if (result.status !== 0) {
  process.stderr.write(result.stderr || 'GraphQL schema export failed\n')
  process.exit(result.status ?? 1)
}
const filename = catalog ? 'error-catalog.json' : management ? 'management-scopes.json' : 'schema.graphql'
const outputs = [['graphql/' + filename, result.stdout]]
if (catalog) outputs.push(['packages/graphql-access/src/error-codes.ts', errorCodeModule(result.stdout)])

for (const [relative, content] of outputs) {
  const path = new URL('../' + relative, import.meta.url)
  if (process.argv.includes('--check')) {
    let current
    try { current = readFileSync(path, 'utf8') } catch { current = undefined }
    if (current !== content) {
      process.stderr.write(relative + ' differs from the executable contract\n')
      process.exit(1)
    }
  } else {
    mkdirSync(new URL('.', path), { recursive: true })
    writeFileSync(path, content, 'utf8')
  }
}

/** Named numeric codes, grouped like the Rust enums that define them. */
function errorCodeModule(json) {
  const groups = new Map()
  for (const { group, name, code } of JSON.parse(json)) {
    if (!groups.has(group)) groups.set(group, [])
    groups.get(group).push([name, code])
  }
  const lines = [
    '// Generated by `pnpm errors:catalog` from graphql/error-catalog.json. Do not edit.',
    '',
  ]
  for (const [group, entries] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`export const ${group} = {`)
    for (const [name, code] of entries.sort(([, a], [, b]) => a - b)) lines.push(`  ${name}: ${code},`)
    lines.push('} as const', '')
  }
  return lines.join('\n')
}
