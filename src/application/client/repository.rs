//! Persistence port for OAuth client management.
//!
//! Every write carries the immutable request authority. Implementations
//! re-check it against authoritative rows inside the write transaction, lock the
//! client, compare its UUID version, permanently withdraw issued artifacts when
//! the client's authorization boundary changes, and append the semantic audit
//! fact before committing.

use std::{error::Error as StdError, sync::Arc};

use async_trait::async_trait;
use chrono::{DateTime, Utc};
use identity_domain::{
    client::model::ClientOid,
    openid_connect::{OpenIdConnectCredentialData, OpenIdConnectCredentialOid},
    rbac::LocalizedText,
};
use uuid::Uuid;

use super::model::{
    ClientCredentialRecord, ClientCredentialResult, ClientCredentialRevokeResult, ClientFilter,
    ClientOrder, ClientProtocolSettings, ClientRecord, ClientSecretResult,
};
use crate::{
    authorization::ManagementAuthorizationError,
    rbac::{
        RbacManagementAuthority,
        cursor::{RbacPageDirection, RbacSortKey},
    },
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClientEntityKind {
    Client,
    Credential,
}

#[derive(Debug, thiserror::Error)]
pub enum ClientManagementRepositoryError {
    #[error("client storage failure")]
    Storage(#[source] Box<dyn StdError + Send + Sync + 'static>),
    #[error("client management authorization recheck failed")]
    Authorization(#[source] ManagementAuthorizationError),
    #[error("client audit commit failed")]
    AuditFailed(#[source] Box<dyn StdError + Send + Sync + 'static>),
    #[error("no recoverable authorization administrator remains")]
    LastRecoverableAdministrator,
    #[error("persisted client record is malformed")]
    CorruptRecord,
    #[error("client record not found: {0:?}")]
    NotFound(ClientEntityKind),
    #[error("optimistic version conflict; current version is {current_version}")]
    VersionConflict { current_version: Uuid },
    #[error("built-in clients are protected")]
    BuiltInProtected,
    #[error("only client secrets can be rotated")]
    CredentialNotSecret,
    #[error("the credential has already been revoked")]
    CredentialRevoked,
    #[error("the client already holds {max} usable credentials of this kind")]
    CredentialLimitReached { max: usize },
}

#[derive(Debug, Clone)]
pub struct ClientPageEntry {
    pub sort_key: RbacSortKey,
    pub record: ClientRecord,
}

#[derive(Debug, Clone)]
pub struct ClientPageData {
    pub items: Vec<ClientPageEntry>,
    pub has_previous_page: bool,
    pub has_next_page: bool,
}

#[derive(Debug, Clone)]
pub struct ClientQuery {
    pub filter: ClientFilter,
    pub order: ClientOrder,
    pub direction: RbacPageDirection,
    pub after: Option<RbacSortKey>,
    pub before: Option<RbacSortKey>,
    pub limit: usize,
}

/// A secret generated by the service. Only the persisted credential data is
/// stored; the plaintext is returned to the caller once.
#[derive(Clone)]
pub struct NewClientSecret {
    pub credential_oid: OpenIdConnectCredentialOid,
    pub data: OpenIdConnectCredentialData,
    pub plaintext: String,
    pub lifetime_days: u32,
}

impl std::fmt::Debug for NewClientSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("NewClientSecret")
            .field("credential_oid", &self.credential_oid)
            .field("lifetime_days", &self.lifetime_days)
            .finish_non_exhaustive()
    }
}

#[derive(Debug, Clone)]
pub struct CreateClientTransaction {
    pub client_oid: ClientOid,
    pub name: String,
    pub description: String,
    pub names: Vec<LocalizedText>,
    pub descriptions: Vec<LocalizedText>,
    pub settings: ClientProtocolSettings,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

#[derive(Debug, Clone)]
pub struct UpdateClientTransaction {
    pub client_oid: ClientOid,
    pub expected_version: Uuid,
    pub name: Option<String>,
    pub description: Option<String>,
    pub names: Option<Vec<LocalizedText>>,
    pub descriptions: Option<Vec<LocalizedText>>,
    pub settings: Option<ClientProtocolSettings>,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

#[derive(Debug, Clone)]
pub struct ClientStateTransaction {
    pub client_oid: ClientOid,
    pub expected_version: Uuid,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

#[derive(Debug, Clone)]
pub struct CreateClientSecretTransaction {
    pub client_oid: ClientOid,
    pub expected_version: Uuid,
    pub replaces: Option<OpenIdConnectCredentialOid>,
    pub secret: NewClientSecret,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

/// Store an already validated key credential. `expires_at` of `None` never
/// expires; `action` names the audit fact.
#[derive(Debug, Clone)]
pub struct AddClientCredentialTransaction {
    pub client_oid: ClientOid,
    pub expected_version: Uuid,
    pub credential_oid: OpenIdConnectCredentialOid,
    pub data: OpenIdConnectCredentialData,
    /// Replaces the stored hint derived from `data`, such as a key thumbprint.
    pub hint: Option<String>,
    pub expires_at: Option<DateTime<Utc>>,
    pub action: &'static str,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

#[derive(Debug, Clone)]
pub struct RevokeClientCredentialTransaction {
    pub client_oid: ClientOid,
    pub credential_oid: OpenIdConnectCredentialOid,
    pub expected_version: Uuid,
    pub reason: String,
    pub authority: RbacManagementAuthority,
}

#[async_trait]
pub trait ClientManagementRepository: Send + Sync {
    async fn count_clients(
        &self,
        filter: ClientFilter,
    ) -> Result<u64, ClientManagementRepositoryError>;

    async fn list_clients(
        &self,
        query: ClientQuery,
    ) -> Result<ClientPageData, ClientManagementRepositoryError>;

    async fn find_client(
        &self,
        oid: ClientOid,
    ) -> Result<Option<ClientRecord>, ClientManagementRepositoryError>;

    /// Metadata of the credentials not revoked, expired ones included, newest
    /// first. Revocation is permanent and recorded in the audit log, so revoked
    /// credentials are not listed. Secret values are never read.
    async fn list_client_credentials(
        &self,
        oid: ClientOid,
    ) -> Result<Vec<ClientCredentialRecord>, ClientManagementRepositoryError>;

    /// Secrets are issued separately so credential creation keeps its own
    /// authority requirement.
    async fn create_client(
        &self,
        command: CreateClientTransaction,
    ) -> Result<ClientRecord, ClientManagementRepositoryError>;

    async fn update_client(
        &self,
        command: UpdateClientTransaction,
    ) -> Result<ClientRecord, ClientManagementRepositoryError>;

    /// Disabling permanently withdraws issued artifacts; enabling never
    /// restores them.
    async fn set_client_enabled(
        &self,
        command: ClientStateTransaction,
        enabled: bool,
    ) -> Result<ClientRecord, ClientManagementRepositoryError>;

    async fn delete_client(
        &self,
        command: ClientStateTransaction,
    ) -> Result<ClientOid, ClientManagementRepositoryError>;

    async fn create_client_secret(
        &self,
        command: CreateClientSecretTransaction,
    ) -> Result<ClientSecretResult, ClientManagementRepositoryError>;

    /// Add a public key or JWKS URI. Existing credentials stay valid.
    async fn add_client_credential(
        &self,
        command: AddClientCredentialTransaction,
    ) -> Result<ClientCredentialResult, ClientManagementRepositoryError>;

    async fn revoke_client_credential(
        &self,
        command: RevokeClientCredentialTransaction,
    ) -> Result<ClientCredentialRevokeResult, ClientManagementRepositoryError>;
}

pub type SharedClientManagementRepository = Arc<dyn ClientManagementRepository>;
