//! Business RBAC management error catalog. Reserved range: 17000-17099.
//!
//! These codes describe resource, scope, permission, role, user-role binding
//! and narrow client-delegation management. Semantically identical management
//! scope boundary failures continue to use the existing 27015/27017 codes and
//! transactional audit failures use 27019.

define_error_codes! {
    pub enum RbacErrorCode(module = "rbac") {
        ValidationFailed = 17000 { kind: Validation, optional: [field] },
        ResourceNotFound = 17001 { kind: NotFound, module: "rbac.resource" },
        ScopeNotFound = 17002 { kind: NotFound, module: "rbac.scope" },
        PermissionNotFound = 17003 { kind: NotFound, module: "rbac.permission" },
        RoleNotFound = 17004 { kind: NotFound, module: "rbac.role" },
        BindingNotFound = 17005 { kind: NotFound, module: "rbac.binding" },
        UserNotFound = 17006 { kind: NotFound, module: "rbac.binding" },
        ClientNotFound = 17007 { kind: NotFound, module: "rbac.client" },
        VersionConflict = 17008 { kind: Conflict, required: [current_version] },
        UserVersionStale = 17009 { kind: Conflict, required: [current_version], module: "rbac.binding" },
        PolicyVersionStale = 17010 { kind: Conflict, required: [current_version], module: "rbac.client" },
        DuplicateResourceUri = 17011 { kind: Conflict, optional: [uri], module: "rbac.resource" },
        DuplicateScopeCode = 17012 { kind: Conflict, optional: [code], module: "rbac.scope" },
        DuplicatePermissionCode = 17013 { kind: Conflict, optional: [code], module: "rbac.permission" },
        DuplicatePermissionScope = 17014 { kind: Conflict, optional: [scope], module: "rbac.permission" },
        ReservedResourceProtected = 17016 { kind: Forbidden, optional: [resource], module: "rbac.resource" },
        BuiltInScopeProtected = 17017 { kind: Forbidden, optional: [name], module: "rbac.scope" },
        ScopeNotAcceptedByResource = 17018 { kind: Validation, required: [scope], optional: [resource], module: "rbac.permission" },
        ScopeReferencedByPermission = 17019 { kind: Conflict, required: [scope], module: "rbac.resource" },
        PolicyDowngradeBlocked = 17020 { kind: Conflict, optional: [resource], module: "rbac.resource" },
        IncompleteScopeMapping = 17021 { kind: Conflict, required: [missing_count], module: "rbac.resource" },
        ClientProtected = 17022 { kind: Forbidden, optional: [client], module: "rbac.client" },
        ClientScopeNotBusiness = 17023 { kind: Validation, required: [scope], module: "rbac.client" },
        RolePermissionLimitExceeded = 17024 { kind: Validation, required: [max], module: "rbac.role" },
        UserRoleLimitExceeded = 17025 { kind: Validation, required: [max], module: "rbac.binding" },
        RoleNotAssigned = 17026 { kind: Conflict, optional: [role_id], module: "rbac.binding" },
        RoleDisabled = 17027 { kind: Conflict, optional: [role_id], module: "rbac.binding" },
        StorageFailed = 17028 { kind: Internal },
        InvalidResourceUri = 17029 { kind: Validation, optional: [uri], module: "rbac.resource" },
        InvalidScopeName = 17030 { kind: Validation, optional: [name], module: "rbac.scope" },
        InvalidScopeDescription = 17031 { kind: Validation, optional: [max], module: "rbac.scope" },
        InvalidPermissionDescription = 17032 { kind: Validation, optional: [max], module: "rbac.permission" },
        InvalidRoleName = 17033 { kind: Validation, optional: [max], module: "rbac.role" },
        InvalidReason = 17035 { kind: Validation, optional: [min, max] },
        InvalidVersion = 17036 { kind: Validation },
        InvalidCursor = 17037 { kind: Validation },
        PageSizeInvalid = 17038 { kind: Validation, required: [max] },
        PageArgumentsConflict = 17039 { kind: Validation },
        InvalidFilter = 17040 { kind: Validation, required: [field], optional: [max] },
        InvalidClientMutationId = 17041 { kind: Validation, required: [max] },
        InvalidCollectionSize = 17042 { kind: Validation, required: [max] },
        EmptyUpdate = 17043 { kind: Validation },
        InvalidPermissionCode = 17045 { kind: Validation, optional: [max], module: "rbac.permission" },
        InvalidDescriptionLocale = 17046 { kind: Validation, optional: [max], module: "rbac.scope" },
        InvalidResourceName = 17047 { kind: Validation, optional: [max], module: "rbac.resource" },
        InvalidLocalizedMetadata = 17048 { kind: Validation, optional: [field, locale, max], module: "rbac.metadata" },
        BuiltInDefinitionProtected = 17049 { kind: Forbidden, optional: [kind, key], module: "rbac.builtin" },
        DelegationCeilingExceeded = 17050 { kind: Forbidden, optional: [permission], module: "rbac.delegation" },
        BuiltInIdentityConflict = 17051 { kind: Internal, optional: [key], module: "rbac.builtin" },
        InvalidBuiltInPermissionReference = 17052 { kind: Validation, optional: [permission], module: "rbac.builtin" },
        ClientGrantNotAllowed = 17053 { kind: Validation, required: [scope], module: "rbac.client" },
    }
}
